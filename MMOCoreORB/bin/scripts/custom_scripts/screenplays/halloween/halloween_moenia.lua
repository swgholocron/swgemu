-- Halloween event at Moenia (Naboo): undead skeleton army, Skeleton King and
-- his pet/executioner. Ported from Flurry (which shipped it disabled); the
-- Outbreak-event creatures it also spawned are intentionally left out.
-- Flip this to false to turn the event off.
HALLOWEEN_EVENT_ENABLED = true

halloween_moenia = ScreenPlay:new {
	numberOfActs = 1,
  	planet = "naboo",
}

registerScreenPlay("halloween_moenia", true)

function halloween_moenia:start()
	Logger:log("Halloween event: start() called, enabled=" .. tostring(HALLOWEEN_EVENT_ENABLED) .. " zoneEnabled=" .. tostring(isZoneEnabled(self.planet)), LT_INFO)

	if (HALLOWEEN_EVENT_ENABLED and isZoneEnabled(self.planet)) then
		self:spawnMobiles()
		self:spawnSceneObjects()
		Logger:log("Halloween event: spawning finished", LT_INFO)
	end
end


